// Convert a "local datetime-local" string (e.g. "2026-10-21T14:30")
// interpreted in the given IANA timezone into a UTC ISO string.
export function localDateTimeInTimezoneToUtc(
  localInput: string,
  timezone: string,
): string {
  // Parse the yyyy-MM-ddTHH:mm parts
  const [datePart, timePart] = localInput.split('T');
  const [year, month, day] = datePart.split('-').map(Number);
  const [hours, minutes] = (timePart || '00:00').split(':').map(Number);

  // Build a UTC Date representing the wall-clock time as if it were in the target tz,
  // then offset by the timezone's offset at that instant.
  const asUtc = Date.UTC(year, month - 1, day, hours, minutes, 0, 0);
  // Compute the timezone offset using Intl
  const tzDate = new Date(asUtc);
  const formatter = new Intl.DateTimeFormat('en-US', {
    timeZone: timezone,
    year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false,
  });
  const parts = formatter.formatToParts(tzDate);
  const get = (type: string) => parts.find((p) => p.type === type)?.value || '0';
  const tzAsUtc = Date.UTC(
    Number(get('year')), Number(get('month')) - 1, Number(get('day')),
    Number(get('hour')) === 24 ? 0 : Number(get('hour')), Number(get('minute')), Number(get('second')),
  );
  const offsetMs = tzAsUtc - asUtc;
  return new Date(asUtc - offsetMs).toISOString();
}
