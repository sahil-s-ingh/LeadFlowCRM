/*
# Add PhonePe Payment Gateway Support

1. Modified Tables
- `platform_payment_settings`
  - Add `active_gateway` (text, default 'razorpay') — selects which payment gateway the checkout uses ('razorpay' or 'phonepe')
  - Add `phonepe_merchant_id` (text, nullable) — PhonePe Merchant ID
  - Add `phonepe_salt_key` (text, nullable) — PhonePe Salt Key (server-side secret, never exposed to frontend)
  - Add `phonepe_salt_index` (text, default '1') — PhonePe Salt Index (1 or 2)
  - Add `phonepe_environment` (text, default 'production') — 'production' or 'sandbox'
- `payment_orders`
  - Add `gateway` (text, default 'razorpay') — which gateway was used ('razorpay' or 'phonepe')
  - Add `phonepe_merchant_txn_id` (text, nullable) — PhonePe merchant transaction ID
  - Add `phonepe_txn_id` (text, nullable) — PhonePe transaction ID (returned after payment)
  - Relax status CHECK constraint to allow 'created', 'paid', 'failed', 'pending'

2. Security
- No new tables. RLS already enabled on both tables.
- PhonePe salt key is stored in the database and only accessed by edge functions via the service role key. It is never sent to the frontend.
- Existing policies remain unchanged — they already allow authenticated and anon access as needed.

3. Important Notes
- The `active_gateway` column lets the super admin switch between Razorpay and PhonePe without losing either set of credentials.
- The checkout drawer will read `active_gateway` to determine which payment flow to trigger.
- PhonePe uses a redirect-based flow (user is redirected to PhonePe's checkout page), unlike Razorpay's popup widget.
- The `phonepe_merchant_txn_id` is generated by our system (unique per order) and used to initiate the payment. The `phonepe_txn_id` is returned by PhonePe after payment completion.
*/

-- Add PhonePe columns to platform_payment_settings
ALTER TABLE platform_payment_settings
  ADD COLUMN IF NOT EXISTS active_gateway text DEFAULT 'razorpay' CHECK (active_gateway IN ('razorpay', 'phonepe'));

ALTER TABLE platform_payment_settings
  ADD COLUMN IF NOT EXISTS phonepe_merchant_id text;

ALTER TABLE platform_payment_settings
  ADD COLUMN IF NOT EXISTS phonepe_salt_key text;

ALTER TABLE platform_payment_settings
  ADD COLUMN IF NOT EXISTS phonepe_salt_index text DEFAULT '1';

ALTER TABLE platform_payment_settings
  ADD COLUMN IF NOT EXISTS phonepe_environment text DEFAULT 'production' CHECK (phonepe_environment IN ('production', 'sandbox'));

-- Add PhonePe columns to payment_orders
ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS gateway text DEFAULT 'razorpay' CHECK (gateway IN ('razorpay', 'phonepe'));

ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS phonepe_merchant_txn_id text;

ALTER TABLE payment_orders
  ADD COLUMN IF NOT EXISTS phonepe_txn_id text;

-- Relax status constraint to allow 'pending' for PhonePe redirect flow
ALTER TABLE payment_orders DROP CONSTRAINT IF EXISTS payment_orders_status_check;
ALTER TABLE payment_orders ADD CONSTRAINT payment_orders_status_check
  CHECK (status IN ('created', 'paid', 'failed', 'pending'));

-- Index for PhonePe transaction lookups
CREATE INDEX IF NOT EXISTS idx_payment_orders_phonepe_merchant_txn_id ON payment_orders(phonepe_merchant_txn_id);
